#!/usr/bin/env python3
"""Pulls the fighter art the idle mode reuses out of a built fight-sim page (index.m*.html or the published page):
the rig drawer (rigJoints, rigPaths, kitPaths, drawKit, drawRig), a few rigs from RIGS, the hair kits (HAIRKITS)
and the idle pose (POSES.idle). Writes src/gen_rigs.js.
Usage: python tools/extract_rigs.py <fight-sim.html>
The fight sim lives in ../../DBZ Fight Sim/src (take the highest index.m*.html)."""
import json, os, re, sys

WANT = ['goku-saiyan', 'goku-ssj', 'krillin', 'gohan-saiyan', 'piccolo-saiyan', 'vegeta-saiyan', 'nappa-saiyan',
        # every Goku and Vegeta look with its own art (Choose Fighter + Forms)
        'goku-buu', 'goku-buu-ssj3-hq', 'vegeta-namek', 'vegeta-buu-base', 'vegeta-buu-ssj', 'vegeta-buu-ssj2']
src = open(sys.argv[1], encoding='utf-8').read()
a = src.index('  const RIG_SCALE = ')
b = src.index('  function drawRig(ctx, rig, J, alpha, hair, kit) {')
b = src.index('\n  }\n', b) + 4
code = src[a:b]
m = re.search(r'\n  const RIGS = (\[.*?\]);\n', src)
rigs = [r for r in json.loads(m.group(1)) if r['id'] in WANT]
missing = set(WANT) - {r['id'] for r in rigs}
if missing:
    raise SystemExit('extract_rigs: not found: %s' % sorted(missing))
# Shulk: SSJ3 Goku's head art faces backwards (face behind, hair in front of him). Mirror the head's shapes across
# the head bone (paths are [along, across] pairs in the bone's frame, so flip "across").
HEAD_FLIP = {'goku-buu-ssj3-hq'}
for r in rigs:
    if r['id'] in HEAD_FLIP:
        for p in r['parts']:
            if p.get('bone') == 'head' and p.get('paths'):
                p['paths'] = [[(-v if k % 2 else v) for k, v in enumerate(pts)] for pts in p['paths']]
m = re.search(r'HAIRKITS = (\{.*?\});\n', src)
kits = json.loads(m.group(1))
m = re.search(r'\n    idle: P\(([^)]*)\),\n', src)
if not m:
    raise SystemExit('extract_rigs: POSES.idle not found')
# the sim's P(lean, head, a1, a2, l1, l2, air, rot)
idle = 'P(' + m.group(1) + ')'
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'gen_rigs.js')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/extract_rigs.py from the DBZ Fight Simulator build. Do not edit by hand.\n')
    f.write('// Fighter art (rigs, hair kits, the idle pose) and the rig drawer, unchanged from the fight sim.\n')
    f.write('const FS_RIGS = (() => {\n')
    f.write(code)
    f.write('  const RIGS = ' + json.dumps(rigs, separators=(',', ':')) + ';\n')
    f.write('  const HAIRKITS = ' + json.dumps(kits, separators=(',', ':')) + ';\n')
    f.write('  const P = (lean, head, a1, a2, l1, l2, air, rot) => ({ lean, head, a1, a2, l1, l2, air: air || 0, rot: rot || 0 });\n')
    f.write('  const POSES = { idle: ' + idle + ' };\n')
    f.write('  return { RIGS, HAIRKITS, POSES, rigJoints, drawRig };\n})();\n')
print('wrote', out, os.path.getsize(out), 'bytes;', ', '.join(r['id'] + ' (' + str(r.get('credit')) + ')' for r in rigs),
      '; kits:', ', '.join(kits))
